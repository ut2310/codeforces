using namespace std;
#include <bits/stdc++.h>
#define ll long long

int main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);  
    ll t; cin >> t;
    while(t-->0)
    {
        ll n; cin >> n;
        for(int i = 1; i <= n; i++)
        {
            cout << i << " ";
        }
        cout << "\n";
    }
}
